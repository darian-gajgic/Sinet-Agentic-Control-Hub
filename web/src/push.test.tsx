// ── subscribe/unsubscribe, and the gesture rule ────────────────────────────

function fakeSubscription(endpoint = 'https://web.push.apple.com/abc'): PushSubscriptionLike & { unsubscribed: boolean } {
  const s = {
    endpoint,
    unsubscribed: false,
    toJSON: () => ({ endpoint, keys: { p256dh: 'BPUB', auth: 'AUTH' } }),
    unsubscribe: async () => {
      s.unsubscribed = true
      return true
    },
  }
  return s
}

function fakeManager(existing: PushSubscriptionLike | null = null) {
  const calls: { userVisibleOnly: boolean; applicationServerKey: Uint8Array }[] = []
  let held = existing
  const manager: PushManagerLike & { calls: typeof calls } = {
    calls,
    getSubscription: async () => held,
    subscribe: async (options) => {
      calls.push(options)
      held = fakeSubscription()
      return held
    },
  }
  return manager
}

function fakeContainer(manager = fakeManager()) {
  const registered: string[] = []
  return {
    registered,
    register: async (script: string) => {
      registered.push(script)
      return { pushManager: manager }
    },
    ready: Promise.resolve({ pushManager: manager }),
  }
}

