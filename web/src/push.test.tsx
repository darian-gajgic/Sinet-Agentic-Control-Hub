describe('a push navigate path resolves to the card it names', () => {
  const fx = JSON.parse(navigateFixture) as { cases: { card_id: string; path: string }[] }

  test('every server-composed path round-trips through the router', () => {
    // The floor: this fixture is GENERATED by internal/api, so an empty one
    // would make the whole tie vacuous.
    expect(fx.cases.length).toBeGreaterThan(5)
    for (const c of fx.cases) {
      const match = matchRoute(c.path)
      expect(match.route.id, `${c.path} did not resolve to the inbox card surface`).toBe('inbox-item')
      expect(match.params.id, `${c.path} resolved to a DIFFERENT card id`).toBe(c.card_id)
    }
  })

  test('and the client composes the same path the server did', () => {
    // The other direction: the SPA's own link builder must produce byte-for-byte
    // what the notifier put in the payload. If these ever diverge, a tapped
    // notification and a clicked link go to different places.
    for (const c of fx.cases) {
      expect(hrefFor('inbox-item', { id: c.card_id }), `hrefFor disagrees with the server for ${c.card_id}`).toBe(c.path)
    }
  })

  test('the tie is not vacuous: the ids really do carry the hard characters', () => {
    const ids = fx.cases.map((c) => c.card_id).join('')
    expect(ids).toContain(':')
    expect(ids).toContain('#')
    expect(ids).toContain('')
    // And at least one path really is escaped, so "round-trips" is a statement
    // about encoding rather than about ids that needed none.
    expect(fx.cases.some((c) => c.path.includes('%'))).toBe(true)
  })
})

