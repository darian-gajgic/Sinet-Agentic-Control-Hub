/** renderedStrings collects every text node and every attribute value under a
 *  node — the whole rendered surface, without serializing it to markup. */
function renderedStrings(root: Element): string[] {
  const out: string[] = []
  const walk = (el: Element) => {
    for (const attr of Array.from(el.attributes)) out.push(attr.value)
    for (const child of Array.from(el.childNodes)) {
      if (child.nodeType === 3) out.push(child.textContent ?? '')
      else if (child.nodeType === 1) walk(child as Element)
    }
  }
  walk(root)
  return out
}

